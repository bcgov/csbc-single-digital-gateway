import { existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import pkg from '../package.json';
import {
  buildExportsMap,
  buildRootEntry,
  discoverSubmodules,
  flatEntryName,
  hasStyles,
} from '../scripts/gen-entries.mjs';
import type { FormStudioProps } from '../src/index';

const root = resolve(import.meta.dirname, '..');
const exportsMap = pkg.exports as Record<string, Record<string, string>>;
// Module subpaths only — a file export such as ./styles.css carries development/default instead.
const moduleEntries = Object.entries(exportsMap).filter(([key]) => !key.endsWith('.css'));

describe('@repo/forms exports map', () => {
  it('gives every module subpath a dev (source) + prod (dist) condition', () => {
    expect(moduleEntries.length).toBeGreaterThan(0);
    for (const [key, value] of moduleEntries) {
      expect(value, key).toMatchObject({
        types: expect.stringContaining('./dist/'),
        development: expect.stringContaining('./src/'),
        import: expect.stringContaining('./dist/'),
        require: expect.stringContaining('./dist/'),
      });
    }
  });

  it('orders conditions types, development, import, require', () => {
    // Order is significant to resolvers: `development` must be offered before `import`/`require`
    // so a dev server takes source over dist (feature 06).
    for (const [key, value] of moduleEntries) {
      expect(Object.keys(value), key).toEqual(['types', 'development', 'import', 'require']);
    }
  });

  it('exposes the studio submodule at ./studio', () => {
    expect(exportsMap['./studio']).toEqual({
      types: './dist/studio.d.ts',
      development: './src/studio.ts',
      import: './dist/studio.js',
      require: './dist/studio.cjs',
    });
  });

  it('keeps the root export types-only — src/index.ts re-exports ./types and nothing else', () => {
    expect(exportsMap['.']).toEqual({
      types: './dist/index.d.ts',
      development: './src/index.ts',
      import: './dist/index.js',
      require: './dist/index.cjs',
    });
    expect(readFileSync(resolve(root, 'src/index.ts'), 'utf8')).toBe(buildRootEntry());
    expect(buildRootEntry()).toBe("export * from './types/index';\n");
  });

  it('has a generated flat entry file for every exported subpath', () => {
    for (const [key] of moduleEntries) {
      // Nested subpaths use a flat entry file: ./renderers/ui → src/renderers-ui.ts (doc 180).
      const name = key === '.' ? 'index' : flatEntryName(key.slice('./'.length));
      expect(existsSync(resolve(root, `src/${name}.ts`)), `src/${name}.ts`).toBe(true);
    }
  });

  it('is regenerated by gen:entries without changing the committed map', () => {
    // Guards against a hand-edited exports map drifting from the source tree.
    expect(exportsMap).toEqual(
      buildExportsMap(discoverSubmodules(root), { styles: hasStyles(root) }),
    );
    expect(discoverSubmodules(root)).toContain('studio');
  });
});

// Doc 180 — nested renderer submodules, the static stylesheet export, and packaging.
describe('@repo/forms renderer submodules', () => {
  it('exposes ./renderers/ui, ./renderers/gridstack, ./renderers/default and ./renderers/studio via flat renderers-* entries', () => {
    for (const name of ['ui', 'gridstack', 'default', 'studio']) {
      expect(exportsMap[`./renderers/${name}`], name).toEqual({
        types: `./dist/renderers-${name}.d.ts`,
        development: `./src/renderers-${name}.ts`,
        import: `./dist/renderers-${name}.js`,
        require: `./dist/renderers-${name}.cjs`,
      });
      expect(readFileSync(resolve(root, `src/renderers-${name}.ts`), 'utf8')).toBe(
        `export * from './renderers/${name}/index';\n`,
      );
    }
    // src/renderers/ has no index — it is a namespace, never a subpath of its own.
    expect(exportsMap).not.toHaveProperty(['./renderers']);
  });

  it('exposes ./styles.css as a non-module export resolving to src in development and dist by default', () => {
    expect(exportsMap['./styles.css']).toEqual({
      development: './src/styles.css',
      default: './dist/styles.css',
    });
    // development must precede default so a dev server takes source over dist.
    expect(Object.keys(exportsMap['./styles.css'] ?? {})).toEqual(['development', 'default']);
    expect(existsSync(resolve(root, 'src/styles.css'))).toBe(true);
  });

  it('ships a src/styles.css that imports gridstack/dist/gridstack.css', () => {
    const css = readFileSync(resolve(root, 'src/styles.css'), 'utf8');
    expect(css).toMatch(/@import\s+['"]gridstack\/dist\/gridstack\.css['"]/);
    // The import must resolve from the package — gridstack is hoisted to the root node_modules.
    expect(existsSync(resolve(root, '../../node_modules/gridstack/dist/gridstack.css'))).toBe(true);
  });

  it('declares sideEffects ["**/*.css"] and depends on @jsonforms/core, @jsonforms/react, @repo/ui and gridstack', () => {
    // sideEffects:false would let production bundlers tree-shake the stylesheet import away.
    expect(pkg.sideEffects).toEqual(['**/*.css']);
    expect(pkg.dependencies).toMatchObject({
      '@jsonforms/core': '3.8.0',
      '@jsonforms/react': '3.8.0',
      '@repo/ui': '*',
      gridstack: '13.2.0',
    });
  });
});

describe('@repo/forms public types', () => {
  it('exports FormStudioProps from the package root', () => {
    // The assignment is the real assertion — it only compiles if FormStudioProps is exported
    // from the root entry and admits exactly the empty object.
    const props: FormStudioProps = {};
    expect(props).toEqual({});
    expect(readFileSync(resolve(root, 'src/types/index.ts'), 'utf8')).toContain(
      'export type FormStudioProps',
    );
  });
});
